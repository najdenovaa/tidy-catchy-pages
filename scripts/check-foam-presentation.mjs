import {chromium} from 'playwright';
import {mkdirSync} from 'node:fs';
const browser=await chromium.launch({headless:true,channel:'chrome'});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('dialog',d=>d.accept());
await page.goto('http://127.0.0.1:8080/cementing/program');
await page.getByRole('button',{name:'Загрузить пример',exact:true}).click();
await page.getByRole('button',{name:/^Ввод/}).click();
await page.getByRole('tab',{name:'Пена',exact:true}).click();
const panel=page.locator('[data-tab-content="foam"]');
await panel.getByRole('button',{name:'Рассчитать программу',exact:true}).click();
const editor=panel.getByTestId('chart-presentation-editor');
await editor.waitFor({state:'visible',timeout:120000});
await editor.locator('summary').click();
await editor.getByLabel('Заголовок графика',{exact:true}).fill('Пена: контроль оформления');
await editor.getByLabel('Шрифт графика',{exact:true}).selectOption('serif');
await editor.getByLabel('Размер шрифта графика',{exact:true}).fill('20');
await editor.getByLabel('left Min',{exact:true}).fill('0');
await editor.getByLabel('left Max',{exact:true}).fill('1');
await editor.getByRole('button',{name:'Применить оформление',exact:true}).click();
const graph=panel.getByRole('img',{name:'Пена: контроль оформления',exact:true});
await graph.waitFor();
if(!(await graph.locator('svg').getAttribute('font-family')).includes('Serif'))throw Error('Gallery font did not update');
if(!(await graph.textContent()).includes('За пределами окна'))throw Error('Missing clipped-data warning');
if(await panel.getByText('Исходные данные изменились',{exact:false}).count())throw Error('Presentation invalidated physics');
await editor.getByLabel('График для оформления',{exact:true}).selectOption('foamDepthPressure');
await editor.getByLabel('Заголовок графика',{exact:true}).fill('Профиль пены');
await editor.getByLabel('left Min',{exact:true}).fill('0');
await editor.getByLabel('left Max',{exact:true}).fill('1');
await editor.getByRole('button',{name:'Применить оформление',exact:true}).click();
await panel.getByLabel('Пена: единица давления',{exact:true}).selectOption('psi');
if(await editor.getByLabel('left Min',{exact:true}).inputValue()!=='')throw Error('Old MPa bounds applied to psi');
await panel.getByRole('img',{name:'Профиль пены',exact:true}).waitFor();
if(!(await editor.textContent()).includes('Прежние пределы'))throw Error('Missing units warning');
mkdirSync('/tmp/foam-presentation',{recursive:true});
for(const width of [1440,390]){
 await page.setViewportSize({width,height:1000});await editor.scrollIntoViewIfNeeded();
 await page.screenshot({path:`/tmp/foam-presentation/${width}.png`});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2);
 if(overflow)throw Error('Horizontal page overflow at '+width);
}
if(errors.length)throw Error(errors.join('; '));
console.log('FOAM_PRESENTATION_OK: gallery, units, retained calculation, desktop/mobile');
await browser.close();
