import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PdfEngine } from '../../public/pdf-editor/pdf.js';
import { coreFonts, textBlock, wrapText } from '../../public/pdf-editor/layout.js';
import { resizeTextBox, moveTextBox } from '../../public/pdf-editor/text-box.js';
const root = new URL('../../public/pdf-editor/', import.meta.url);
const assets = await Promise.all(coreFonts.flatMap(family => ['Regular', 'Bold', 'Italic', 'BoldItalic'].map(face => readFile(new URL(`fonts/${family.replaceAll(' ', '')}-${face}.ttf`, root)))));
const engine = await PdfEngine.initialize(await readFile(new URL('vendor/pdfium.wasm', root)), assets);
engine.open(await readFile(new URL('demo.pdf', root)));
engine.addScanLayer(2, [{ text: 'Исходный текст', box: [.2, .3, .38, .32], background: [255,255,255] }]);
let page = engine.render(2, 595, 842, true);
let selected = page.objects.find(object => object.blockSpec?.scanCover);
assert.ok(selected, 'recognised scan text exists');
let draft = { ...textBlock(selected, page, new Set()), mode: 'text', size: 12, originalSize: 12, shift: false, bold: false, italic: false, color: [20,20,20,255] };
const raw = structuredClone(draft.scanCover.raw);
const text = 'Новый расширенный текст после распознавания';
draft.text = text;
resizeTextBox(draft, 350, page); moveTextBox(draft, 80, 420, page);
const metrics = engine.fontMetrics(draft.font, false, false);
const lines = wrapText(text, draft.width - 2, value => [...value].reduce((sum, char) => sum + metrics.advance(char) * draft.size, 0));
assert.equal(lines.length, 1, 'wider field avoids the previous unwanted line break');
engine.writeBlock(2, { ...draft, lines, delta: 0 });
engine.open(engine.save());
page = engine.render(2, 595, 842, true);
selected = page.objects.find(object => object.blockSpec?.text === text);
let reopened = textBlock(selected, page, new Set());
assert.equal(reopened.width, 350); assert.ok(Math.abs(reopened.x - 80) < .1);
assert.ok(Math.abs(reopened.baseline - draft.baseline) < .1);
assert.deepEqual(reopened.scanCover.raw, raw);
// A second movement must use the new text position, not the old scan erasure's bounds.
assert.ok(reopened.y > 400);
const previous = reopened.baseline;
reopened = { ...reopened, mode: 'text', size: 12, originalSize: 12, shift: false, color: [20,20,20,255] };
moveTextBox(reopened, 100, reopened.y + 30, page);
engine.writeBlock(2, { ...reopened, lines, delta: 0 });
engine.open(engine.save());
const again = engine.render(2, 595, 842, true).objects.find(object => object.blockSpec?.text === text);
assert.ok(Math.abs(again.baseline * page.pageHeight - previous - 30) < .1);
assert.deepEqual(again.blockSpec.scanCover.raw, raw);
engine.clear();
console.log('OCR text width and repeated movement survive PDF save/reopen; old scan erasure remains anchored.');
