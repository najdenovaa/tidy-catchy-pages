import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{channel:'chrome'}),args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));page.on('dialog',d=>d.accept());
await page.goto('http://127.0.0.1:8080/cementing/program');
await page.locator('[data-cementing-program]').waitFor();
await page.getByRole('button',{name:'Загрузить пример',exact:true}).click();
await page.getByRole('button',{name:/^Ввод/}).click();
await page.getByRole('tab',{name:'Центрация (со спуском)',exact:true}).click();
await page.getByRole('button',{name:'Добавить точку',exact:true}).click();
const panel=page.locator('[data-tab-content="centralization"]');
await page.getByRole('spinbutton',{name:/^Глубина турбулизатора/}).first().fill('1000');
await page.getByRole('region',{name:'3D турбулизатора и вихревого потока'}).waitFor();
const target=page.getByRole('region',{name:'3D турбулизатора и вихревого потока'});
const controller=page.locator('[data-turbulator-control]');
const slider=page.getByRole('slider',{name:'Производительность насосов',exact:true});
const beforeSpeed=await controller.locator('[data-flow-metric="Скорость вверх"]').innerText();
const beforeDuration=Number(await target.locator('[data-flow-transit-s]').getAttribute('data-flow-transit-s'));
const initialInterval=await controller.locator('[data-turbulator-interval]').innerText();
await slider.focus();await slider.press('End');
assert.equal(Number(await page.getByLabel('Расход турбулизатора',{exact:true}).inputValue()),Number(await slider.getAttribute('max')));
assert.notEqual(await controller.locator('[data-flow-metric="Скорость вверх"]').innerText(),beforeSpeed);
assert.equal(await controller.locator('[data-turbulator-interval]').innerText(),initialInterval);
assert.ok(Number(await target.locator('[data-flow-transit-s]').getAttribute('data-flow-transit-s'))<beforeDuration);
const critical=Number(await controller.getAttribute('data-turbulent-lps'));
if(critical<Number(await slider.getAttribute('max')))assert.equal(await controller.locator('[data-flow-regime]').innerText(),'Турбулентный');
assert.equal(await target.locator('[data-flow-pulsation]').count(),0);
assert.equal(await page.getByLabel('Масштаб закрутки',{exact:true}).count(),0);
assert.equal(await page.getByLabel('Передача закрутки',{exact:true}).count(),0);
assert.equal(await target.locator('[data-calculated-swirl]').count(),1);
assert.equal(await page.getByRole('region',{name:'Длина затухания вращения'}).count(),1);
const pointTable=page.locator('details[data-point-table="turbulator-points"]');
assert.equal(await pointTable.evaluate(el=>el.open),true);
await pointTable.locator('summary').click();
assert.equal(await pointTable.evaluate(el=>el.open),false);
assert.equal(await target.isVisible(),true);
const front=target.locator('[data-flow-tracer="0-0"][data-flow-layer="front"] animateMotion');
const back=target.locator('[data-flow-tracer="0-0"][data-flow-layer="back"] animateMotion');
assert.equal(await front.getAttribute('dur'),await back.getAttribute('dur'));
assert.equal(await front.getAttribute('path'),await back.getAttribute('path'));
await page.getByRole('slider',{name:'Длина окна наблюдения'}).focus();await page.getByRole('slider',{name:'Длина окна наблюдения'}).press('End');
assert.notEqual(await controller.locator('[data-turbulator-interval]').innerText(),initialInterval);
await target.scrollIntoViewIfNeeded();await target.screenshot({path:'/tmp/turbulator-desktop.png'});
await slider.focus();await slider.press('Home');
if(await target.locator('animateMotion').count())throw Error('Particles must stop at zero flow');
assert.equal(await controller.locator('[data-flow-regime]').innerText(),'Насосы остановлены');
await page.getByLabel('Расход турбулизатора',{exact:true}).fill('10');
await page.setViewportSize({width:390,height:1000});await target.scrollIntoViewIfNeeded();await target.screenshot({path:'/tmp/turbulator-mobile.png'});
const widths=await page.evaluate(()=>({page:document.documentElement.scrollWidth,viewport:innerWidth}));
console.log(JSON.stringify({errors,widths,particles:await target.locator('animateMotion').count(),svg:await target.locator('svg').count()}));
await browser.close();
if(errors.length||widths.page>widths.viewport+2)process.exitCode=1;
